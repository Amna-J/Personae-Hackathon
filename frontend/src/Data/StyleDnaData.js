export function calculatePersona(answers) {
  const counts = {};
  Object.values(answers).forEach((persona) => {
    counts[persona] = (counts[persona] || 0) + 1;
  });
  const topKey = Object.entries(counts).sort((a, b) => b[1] - a[1])[0]?.[0] || "effortless-cool";
  return stylePersonas[topKey];
}